using ClosedXML.Excel;
using Meridian.Application.DTOs;

namespace Meridian.Application.Services;

/// <summary>
/// REPORTS DOWNLOAD (Nov 2026): builds the Reports page as an Excel file.
/// Sheet 1 "Summary" = the filters used + key figures. Sheets 2-4 =
/// Department-wise, Customer-Internal and Project-wise, each group row
/// followed by the employees behind it (same as expanding a row on screen).
/// </summary>
public static class ReportsExcelBuilder
{
	private static readonly XLColor Navy = XLColor.FromHtml("#173A5E");
	private static readonly XLColor GroupFill = XLColor.FromHtml("#E7EEF6");
	private static readonly XLColor TotalFill = XLColor.FromHtml("#D5DCE4");
	private static readonly XLColor LabelGrey = XLColor.FromHtml("#4A5563");

	private const string HoursFormat = "0.0";
	private const string PercentFormat = "0%";

	public static byte[] Build(
		ReportsSummaryDto summary,
		string period,
		string department,
		string timesheetStatus,
		string generatedBy,
		DateTime generatedOn)
	{
		using var workbook = new XLWorkbook();

		AddSummarySheet(workbook, summary, period, department, timesheetStatus, generatedBy, generatedOn);
		AddRollupSheet(workbook, "Department-wise", "Department", summary.DepartmentWise);
		AddRollupSheet(workbook, "Customer-Internal", "Customer / Internal", summary.AccountWise);
		AddRollupSheet(workbook, "Project-wise", "Project", summary.ProjectWise);

		using var stream = new MemoryStream();
		workbook.SaveAs(stream);
		return stream.ToArray();
	}

	private static void AddSummarySheet(
		XLWorkbook workbook, ReportsSummaryDto summary,
		string period, string department, string timesheetStatus, string generatedBy, DateTime generatedOn)
	{
		var sheet = workbook.Worksheets.Add("Summary");

		var title = sheet.Cell(1, 1);
		title.Value = "Carbynetech Timesheet – Hours Report";
		title.Style.Font.Bold = true;
		title.Style.Font.FontSize = 14;
		title.Style.Font.FontColor = Navy;

		// The filters this file was generated with.
		var details = new (string Label, string Value)[]
		{
			("Period", period),
			("Department", department),
			("Timesheet status", timesheetStatus),
			("Generated on", generatedOn.ToString("dd MMM yyyy, hh:mm tt")),
			("Generated by", generatedBy),
		};
		var row = 3;
		foreach (var (label, value) in details)
		{
			sheet.Cell(row, 1).Value = label;
			sheet.Cell(row, 1).Style.Font.Bold = true;
			sheet.Cell(row, 1).Style.Font.FontColor = LabelGrey;
			sheet.Cell(row, 2).Value = value;
			row++;
		}

		// Key figures - same numbers as the cards at the top of the Reports page.
		row = 9;
		sheet.Cell(row, 1).Value = "Key figures";
		sheet.Cell(row, 1).Style.Font.Bold = true;
		sheet.Cell(row, 1).Style.Font.FontSize = 12;
		sheet.Cell(row, 1).Style.Font.FontColor = Navy;

		row++;
		WriteHeader(sheet, row, new[] { "Measure", "Hours", "% of total" });

		var total = summary.ActualHours;
		var figures = new (string Label, decimal Hours)[]
		{
			("Actual hours", summary.ActualHours),
			("Billable", summary.BillableHours),
			("Partial billable", summary.TotalPartialBillableHours),
			("Non-billable", summary.NonBillableHours),
		};
		foreach (var (label, hours) in figures)
		{
			row++;
			sheet.Cell(row, 1).Value = label;
			SetHours(sheet.Cell(row, 2), hours);
			SetPercent(sheet.Cell(row, 3), hours, total);
		}

		row += 2;
		sheet.Cell(row, 1).Value = "Resources reporting";
		sheet.Cell(row, 2).Value = summary.ResourcesReporting;
		row++;
		sheet.Cell(row, 1).Value = "Projects in scope";
		sheet.Cell(row, 2).Value = summary.ProjectsInScope;

		sheet.Column(1).Width = 24;
		sheet.Column(2).Width = 30;
		sheet.Column(3).Width = 12;
	}

	private static void AddRollupSheet(XLWorkbook workbook, string sheetName, string groupHeading, IReadOnlyList<ReportRollupRowDto> rows)
	{
		var sheet = workbook.Worksheets.Add(sheetName);

		var headers = new[]
		{
			groupHeading, "Detail", "Employee", "Designation · Department",
			"Total H", "Billable H", "Billable %", "Partial H", "Partial %", "Non-bill H", "Non-bill %",
		};
		WriteHeader(sheet, 1, headers);

		var widths = new double[] { 34, 30, 30, 36, 10, 11, 11, 10, 10, 11, 11 };
		for (var col = 1; col <= widths.Length; col++)
			sheet.Column(col).Width = widths[col - 1];

		var row = 1;
		foreach (var group in rows)
		{
			// Group row (bold, shaded) ...
			row++;
			sheet.Cell(row, 1).Value = group.Key;
			sheet.Cell(row, 2).Value = group.SubLabel;
			WriteHourColumns(sheet, row, group);
			StyleRow(sheet, row, headers.Length, bold: true, fill: GroupFill);

			// ... then one row per employee behind it.
			foreach (var employee in group.Resources ?? Array.Empty<ReportRollupRowDto>())
			{
				row++;
				sheet.Cell(row, 3).Value = employee.Key;
				sheet.Cell(row, 3).Style.Alignment.Indent = 1;
				sheet.Cell(row, 4).Value = employee.SubLabel;
				WriteHourColumns(sheet, row, employee);
				StyleRow(sheet, row, headers.Length, bold: false, fill: null);
			}
		}

		var lastDataRow = row;

		// Total row - the group rows added up.
		row++;
		sheet.Cell(row, 1).Value = "Total";
		var totals = new ReportRollupRowDto(
			"Total", "",
			rows.Sum(r => r.TotalHours),
			rows.Sum(r => r.BillableHours),
			rows.Sum(r => r.PartialBillableHours),
			rows.Sum(r => r.NonBillableHours),
			0);
		WriteHourColumns(sheet, row, totals);
		StyleRow(sheet, row, headers.Length, bold: true, fill: TotalFill);

		sheet.SheetView.FreezeRows(1);
		if (lastDataRow > 1)
			sheet.Range(1, 1, lastDataRow, headers.Length).SetAutoFilter();
	}

	private static void WriteHeader(IXLWorksheet sheet, int row, string[] headers)
	{
		for (var col = 1; col <= headers.Length; col++)
		{
			var cell = sheet.Cell(row, col);
			cell.Value = headers[col - 1];
			cell.Style.Font.Bold = true;
			cell.Style.Font.FontColor = XLColor.White;
			cell.Style.Fill.BackgroundColor = Navy;
			cell.Style.Alignment.WrapText = true;
		}
	}

	/// <summary>Columns E-K: total, then each hour type with its % of the row's total.</summary>
	private static void WriteHourColumns(IXLWorksheet sheet, int row, ReportRollupRowDto data)
	{
		SetHours(sheet.Cell(row, 5), data.TotalHours);
		SetHours(sheet.Cell(row, 6), data.BillableHours);
		SetPercent(sheet.Cell(row, 7), data.BillableHours, data.TotalHours);
		SetHours(sheet.Cell(row, 8), data.PartialBillableHours);
		SetPercent(sheet.Cell(row, 9), data.PartialBillableHours, data.TotalHours);
		SetHours(sheet.Cell(row, 10), data.NonBillableHours);
		SetPercent(sheet.Cell(row, 11), data.NonBillableHours, data.TotalHours);
	}

	private static void StyleRow(IXLWorksheet sheet, int row, int columnCount, bool bold, XLColor? fill)
	{
		for (var col = 1; col <= columnCount; col++)
		{
			var cell = sheet.Cell(row, col);
			cell.Style.Font.Bold = bold;
			cell.Style.Border.BottomBorder = XLBorderStyleValues.Thin;
			cell.Style.Border.BottomBorderColor = TotalFill;
			if (fill is not null) cell.Style.Fill.BackgroundColor = fill;
		}
	}

	private static void SetHours(IXLCell cell, decimal hours)
	{
		cell.Value = (double)hours;
		cell.Style.NumberFormat.Format = HoursFormat;
	}

	private static void SetPercent(IXLCell cell, decimal part, decimal total)
	{
		cell.Value = total == 0 ? 0d : (double)(part / total);
		cell.Style.NumberFormat.Format = PercentFormat;
	}
}
